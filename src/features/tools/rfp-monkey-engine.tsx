"use client";

import { useState } from "react";
import { FileText, Copy, Download, Trash2, Wand2, Loader2, Check, ListChecks, Building2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { Input } from "@/components/ui/input";
import { Card, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Label } from "@/components/ui/label";
import { toast } from "sonner";

const RFP_SECTIONS = [
  "Executive Summary",
  "Company Background",
  "Project Scope & Objectives",
  "Technical Requirements",
  "Timeline & Milestones",
  "Budget & Pricing",
  "Evaluation Criteria",
  "Terms & Conditions",
  "Submission Guidelines",
  "Appendices",
];

export function RFPMonkeyEngine() {
  const [projectName, setProjectName] = useState("");
  const [description, setDescription] = useState("");
  const [selectedSections, setSelectedSections] = useState<string[]>(["Executive Summary", "Project Scope & Objectives", "Technical Requirements"]);
  const [isGenerating, setIsGenerating] = useState(false);
  const [generatedRFP, setGeneratedRFP] = useState("");
  const [copied, setCopied] = useState(false);

  const toggleSection = (section: string) => {
    setSelectedSections((prev) =>
      prev.includes(section) ? prev.filter((s) => s !== section) : [...prev, section]
    );
  };

  const handleGenerate = async () => {
    if (!projectName.trim()) {
      toast.error("Please enter a project name.");
      return;
    }
    if (selectedSections.length === 0) {
      toast.error("Please select at least one section.");
      return;
    }

    setIsGenerating(true);
    // Simulate generation delay
    await new Promise((r) => setTimeout(r, 1500));

    const sections = selectedSections.map((section) => {
      return `## ${section}\n\n` +
        `This section covers the ${section.toLowerCase()} for **${projectName}**.\n\n` +
        (description ? `Context: ${description}\n\n` : "") +
        `[Detailed ${section.toLowerCase()} content to be customized based on your specific requirements.]\n\n` +
        `---\n`;
    });

    const rfp = `# Request for Proposal: ${projectName}\n\n` +
      `**Date:** ${new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })}\n` +
      `**Project:** ${projectName}\n` +
      (description ? `**Description:** ${description}\n\n` : "\n") +
      `---\n\n` +
      sections.join("\n") +
      `\n*Generated by RFP Monkey — customize sections as needed for your specific procurement requirements.*`;

    setGeneratedRFP(rfp);
    setIsGenerating(false);
    toast.success("RFP draft generated!");
  };

  const handleCopy = async () => {
    await navigator.clipboard.writeText(generatedRFP);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
    toast.success("Copied to clipboard!");
  };

  const handleDownload = () => {
    const blob = new Blob([generatedRFP], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `RFP-${projectName.replace(/\s+/g, "-").toLowerCase()}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-4">
      <div className="flex items-center gap-2 mb-2">
        <Badge variant="secondary" className="rounded-full">RFP Monkey</Badge>
        <span className="text-xs text-muted-foreground">Automate drafting RFP documents</span>
      </div>

      {/* Input fields */}
      <div className="space-y-3">
        <div>
          <Label className="text-sm font-medium">Project Name</Label>
          <Input
            placeholder="e.g., Office Network Infrastructure Upgrade"
            value={projectName}
            onChange={(e) => setProjectName(e.target.value)}
            className="rounded-xl mt-1"
          />
        </div>
        <div>
          <Label className="text-sm font-medium">Project Description (optional)</Label>
          <Textarea
            placeholder="Brief description of what you're procuring..."
            value={description}
            onChange={(e) => setDescription(e.target.value)}
            className="rounded-xl mt-1 min-h-20"
          />
        </div>
      </div>

      {/* Section selector */}
      <div>
        <Label className="text-sm font-medium mb-2 block">RFP Sections</Label>
        <div className="grid grid-cols-2 sm:grid-cols-3 gap-2">
          {RFP_SECTIONS.map((section) => (
            <button
              key={section}
              onClick={() => toggleSection(section)}
              className={`p-2 rounded-xl border text-xs font-medium text-left transition-all ${
                selectedSections.includes(section)
                  ? "border-primary bg-primary/5 ring-1 ring-primary/20"
                  : "border-border/50 hover:border-border hover:bg-muted/30"
              }`}
            >
              <ListChecks className={`h-3.5 w-3.5 inline mr-1.5 ${selectedSections.includes(section) ? "text-primary" : "text-muted-foreground"}`} />
              {section}
            </button>
          ))}
        </div>
      </div>

      {/* Generate button */}
      <Button
        onClick={handleGenerate}
        disabled={!projectName.trim() || selectedSections.length === 0 || isGenerating}
        className="gap-2 rounded-xl w-full sm:w-auto"
      >
        {isGenerating ? <Loader2 className="h-4 w-4 animate-spin" /> : <Wand2 className="h-4 w-4" />}
        {isGenerating ? "Generating..." : "Generate RFP Draft"}
      </Button>

      {/* Generated RFP */}
      {generatedRFP && (
        <div className="space-y-3">
          <div className="flex items-center justify-between">
            <h3 className="font-medium text-sm flex items-center gap-2">
              <Building2 className="h-4 w-4" />
              Generated RFP
            </h3>
            <div className="flex gap-1">
              <Button variant="ghost" size="sm" onClick={handleCopy} className="gap-1.5 h-7">
                {copied ? <Check className="h-3.5 w-3.5 text-green-500" /> : <Copy className="h-3.5 w-3.5" />}
                {copied ? "Copied" : "Copy"}
              </Button>
              <Button variant="ghost" size="sm" onClick={handleDownload} className="gap-1.5 h-7">
                <Download className="h-3.5 w-3.5" />
                Download
              </Button>
            </div>
          </div>
          <Card className="border-border/50">
            <CardContent className="p-4">
              <pre className="text-sm whitespace-pre-wrap font-mono bg-muted/30 p-4 rounded-xl max-h-100 overflow-y-auto">
                {generatedRFP}
              </pre>
            </CardContent>
          </Card>
        </div>
      )}

      {!generatedRFP && (
        <div className="text-center py-6 text-muted-foreground">
          <Building2 className="h-10 w-10 mx-auto mb-3 opacity-30" />
          <p className="text-sm">Enter a project name and select sections to generate an RFP draft</p>
        </div>
      )}
    </div>
  );
}