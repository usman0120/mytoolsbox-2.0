"use client";

import { useState, useMemo } from "react";
import {
  Calendar,
  Download,
  Copy,
  Check,
  Sparkles,
  Gift,
  Clock,
  Heart,
  Compass,
  ArrowRightLeft,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Card, CardContent } from "@/components/ui/card";
import {
  calculateComprehensiveAge,
  dateDifference,
  ComprehensiveAge,
} from "@/features/tools/age-calculator";
import { toast } from "sonner";

export function AgeCalculatorEngine() {
  const [mode, setMode] = useState<"birthday" | "difference">("birthday");
  const [birthDate, setBirthDate] = useState("1998-05-15");
  const [asOfDate, setAsOfDate] = useState(
    new Date().toISOString().split("T")[0]
  );
  const [date1, setDate1] = useState("2020-01-01");
  const [date2, setDate2] = useState("2025-12-31");
  const [copied, setCopied] = useState(false);

  const comprehensiveResult: ComprehensiveAge | null = useMemo(() => {
    if (!birthDate) return null;
    const b = new Date(birthDate);
    const target = asOfDate ? new Date(asOfDate) : new Date();
    if (isNaN(b.getTime()) || isNaN(target.getTime())) return null;
    return calculateComprehensiveAge(b, target);
  }, [birthDate, asOfDate]);

  const diffResult = useMemo(() => {
    if (!date1 || !date2) return null;
    const d1 = new Date(date1);
    const d2 = new Date(date2);
    if (isNaN(d1.getTime()) || isNaN(d2.getTime())) return null;
    return dateDifference(d1, d2);
  }, [date1, date2]);

  const handleCopy = async () => {
    if (!comprehensiveResult) return;
    const r = comprehensiveResult;
    const summary =
      `Exact Age: ${r.years} years, ${r.months} months, ${r.days} days\n` +
      `Born on: ${r.dayOfWeekBorn}\n` +
      `Next Birthday: in ${r.nextBirthday.daysUntil} days (${r.nextBirthday.dateFormatted})\n` +
      `Zodiac Sign: ${r.zodiac.sign} ${r.zodiac.symbol} (${r.zodiac.element})`;
    await navigator.clipboard.writeText(summary);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
    toast.success("Age summary copied!");
  };

  const handleDownload = () => {
    if (!comprehensiveResult) return;
    const r = comprehensiveResult;
    const report =
      `========================================\n` +
      `        OFFICIAL AGE AUDIT REPORT       \n` +
      `========================================\n\n` +
      `Birth Date:        ${birthDate}\n` +
      `Calculated As Of:  ${asOfDate}\n` +
      `Day of Week Born:  ${r.dayOfWeekBorn}\n\n` +
      `EXACT CHRONOLOGICAL AGE:\n` +
      `  • ${r.years} Years, ${r.months} Months, and ${r.days} Days\n\n` +
      `CUMULATIVE MILESTONES:\n` +
      `  • Total Months:   ${r.totalMonths.toLocaleString()} months\n` +
      `  • Total Weeks:    ${r.totalWeeks.toLocaleString()} weeks\n` +
      `  • Total Days:     ${r.totalDays.toLocaleString()} days\n` +
      `  • Total Hours:    ~${r.totalHours.toLocaleString()} hours\n` +
      `  • Total Minutes:  ~${r.totalMinutes.toLocaleString()} minutes\n\n` +
      `UPCOMING BIRTHDAY:\n` +
      `  • Days Remaining: ${r.nextBirthday.daysUntil} days\n` +
      `  • Turning Age:    ${r.nextBirthday.turningAge} years old\n` +
      `  • Birthday Date:  ${r.nextBirthday.dateFormatted} (${r.nextBirthday.dayOfWeek})\n\n` +
      `ASTROLOGICAL PROFILE:\n` +
      `  • Zodiac Sign:    ${r.zodiac.sign} ${r.zodiac.symbol}\n` +
      `  • Element:        ${r.zodiac.element}\n\n` +
      `Generated by MyToolsBox.me Analytics Suite\n`;

    const blob = new Blob([report], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `age-report-${birthDate}.txt`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success("Downloaded detailed age audit report!");
  };

  return (
    <div className="space-y-6">
      {/* Mode Switcher */}
      <div className="flex items-center gap-2 p-1.5 bg-muted/50 rounded-xl border w-fit">
        <Button
          variant={mode === "birthday" ? "default" : "ghost"}
          size="sm"
          onClick={() => setMode("birthday")}
          className="text-xs h-8 gap-1.5"
        >
          <Calendar className="h-3.5 w-3.5" /> Age from Birth Date
        </Button>
        <Button
          variant={mode === "difference" ? "default" : "ghost"}
          size="sm"
          onClick={() => setMode("difference")}
          className="text-xs h-8 gap-1.5"
        >
          <ArrowRightLeft className="h-3.5 w-3.5" /> Date Difference
        </Button>
      </div>

      {mode === "birthday" ? (
        <>
          {/* Inputs Card */}
          <div className="rounded-xl border bg-card p-5 shadow-xs">
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div>
                <Label className="text-xs font-semibold mb-1.5 block">
                  Date of Birth
                </Label>
                <Input
                  type="date"
                  value={birthDate}
                  onChange={(e) => setBirthDate(e.target.value)}
                  className="h-10 text-sm font-mono"
                />
              </div>
              <div>
                <Label className="text-xs font-semibold mb-1.5 block">
                  Calculate Age As Of (Default: Today)
                </Label>
                <Input
                  type="date"
                  value={asOfDate}
                  onChange={(e) => setAsOfDate(e.target.value)}
                  className="h-10 text-sm font-mono"
                />
              </div>
            </div>
          </div>

          {/* Results Grid */}
          {comprehensiveResult && (
            <div className="space-y-4">
              {/* Primary Age Banner */}
              <div className="rounded-2xl border bg-gradient-to-r from-primary/10 via-primary/5 to-transparent p-6 shadow-xs flex flex-wrap items-center justify-between gap-4">
                <div>
                  <span className="text-xs font-semibold uppercase tracking-wider text-muted-foreground block mb-1">
                    Your Exact Age
                  </span>
                  <div className="flex items-baseline gap-3 flex-wrap">
                    <span className="text-3xl sm:text-4xl font-extrabold text-foreground font-mono">
                      {comprehensiveResult.years} <span className="text-lg font-normal text-muted-foreground">years</span>
                    </span>
                    <span className="text-3xl sm:text-4xl font-extrabold text-foreground font-mono">
                      {comprehensiveResult.months} <span className="text-lg font-normal text-muted-foreground">months</span>
                    </span>
                    <span className="text-3xl sm:text-4xl font-extrabold text-foreground font-mono">
                      {comprehensiveResult.days} <span className="text-lg font-normal text-muted-foreground">days</span>
                    </span>
                  </div>
                  <p className="text-xs text-muted-foreground mt-2">
                    Born on a <span className="font-semibold text-foreground">{comprehensiveResult.dayOfWeekBorn}</span>
                  </p>
                </div>

                <div className="flex items-center gap-2">
                  <Button variant="outline" size="sm" onClick={handleCopy} className="gap-1.5 h-8 text-xs">
                    {copied ? <Check className="h-3.5 w-3.5 text-emerald-500" /> : <Copy className="h-3.5 w-3.5" />}
                    Copy
                  </Button>
                  <Button variant="outline" size="sm" onClick={handleDownload} className="gap-1.5 h-8 text-xs">
                    <Download className="h-3.5 w-3.5" /> Download Report
                  </Button>
                </div>
              </div>

              {/* Next Birthday & Zodiac Cards */}
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                <Card className="shadow-xs">
                  <CardContent className="p-4 flex items-center gap-3.5">
                    <div className="h-11 w-11 rounded-xl bg-amber-500/10 text-amber-600 flex items-center justify-center shrink-0">
                      <Gift className="h-5 w-5" />
                    </div>
                    <div>
                      <span className="text-xs font-semibold text-muted-foreground uppercase tracking-wider block">
                        Next Birthday
                      </span>
                      <p className="text-sm font-bold mt-0.5">
                        In {comprehensiveResult.nextBirthday.daysUntil} days
                        <span className="text-xs font-normal text-muted-foreground ml-1.5">
                          (Turning {comprehensiveResult.nextBirthday.turningAge})
                        </span>
                      </p>
                      <p className="text-xs text-muted-foreground mt-0.5">
                        {comprehensiveResult.nextBirthday.dateFormatted} ({comprehensiveResult.nextBirthday.dayOfWeek})
                      </p>
                    </div>
                  </CardContent>
                </Card>

                <Card className="shadow-xs">
                  <CardContent className="p-4 flex items-center gap-3.5">
                    <div className="h-11 w-11 rounded-xl bg-purple-500/10 text-purple-600 flex items-center justify-center shrink-0 text-xl font-bold">
                      {comprehensiveResult.zodiac.symbol}
                    </div>
                    <div>
                      <span className="text-xs font-semibold text-muted-foreground uppercase tracking-wider block">
                        Astrological Sign
                      </span>
                      <p className="text-sm font-bold mt-0.5">
                        {comprehensiveResult.zodiac.sign}
                        <span className="text-xs font-normal text-muted-foreground ml-1.5">
                          ({comprehensiveResult.zodiac.element} Sign)
                        </span>
                      </p>
                      <p className="text-xs text-muted-foreground mt-0.5">
                        Zodiac alignment for birth date
                      </p>
                    </div>
                  </CardContent>
                </Card>
              </div>

              {/* Cumulative Lifetime Units */}
              <div className="rounded-xl border bg-card p-5 shadow-xs space-y-3">
                <h4 className="text-xs font-semibold text-muted-foreground uppercase tracking-wider">
                  Lifetime Milestones Achieved
                </h4>
                <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
                  <div className="p-3 bg-muted/30 rounded-xl border text-center">
                    <span className="text-lg font-bold font-mono text-foreground">
                      {comprehensiveResult.totalMonths.toLocaleString()}
                    </span>
                    <span className="text-[11px] text-muted-foreground block">Total Months</span>
                  </div>
                  <div className="p-3 bg-muted/30 rounded-xl border text-center">
                    <span className="text-lg font-bold font-mono text-foreground">
                      {comprehensiveResult.totalWeeks.toLocaleString()}
                    </span>
                    <span className="text-[11px] text-muted-foreground block">Total Weeks</span>
                  </div>
                  <div className="p-3 bg-muted/30 rounded-xl border text-center">
                    <span className="text-lg font-bold font-mono text-foreground">
                      {comprehensiveResult.totalDays.toLocaleString()}
                    </span>
                    <span className="text-[11px] text-muted-foreground block">Total Days</span>
                  </div>
                  <div className="p-3 bg-muted/30 rounded-xl border text-center">
                    <span className="text-lg font-bold font-mono text-foreground">
                      ~{comprehensiveResult.totalHours.toLocaleString()}
                    </span>
                    <span className="text-[11px] text-muted-foreground block">Total Hours</span>
                  </div>
                </div>
              </div>
            </div>
          )}
        </>
      ) : (
        /* Date Difference Mode */
        <div className="space-y-4">
          <div className="rounded-xl border bg-card p-5 shadow-xs space-y-4">
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div>
                <Label className="text-xs font-semibold mb-1.5 block">Start Date</Label>
                <Input
                  type="date"
                  value={date1}
                  onChange={(e) => setDate1(e.target.value)}
                  className="h-10 text-sm font-mono"
                />
              </div>
              <div>
                <Label className="text-xs font-semibold mb-1.5 block">End Date</Label>
                <Input
                  type="date"
                  value={date2}
                  onChange={(e) => setDate2(e.target.value)}
                  className="h-10 text-sm font-mono"
                />
              </div>
            </div>
          </div>

          {diffResult && (
            <div className="rounded-2xl border bg-card p-6 shadow-xs text-center space-y-3">
              <span className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">
                Time Interval Between Dates
              </span>
              <div className="flex items-center justify-center gap-3 flex-wrap font-mono text-2xl sm:text-3xl font-bold">
                <span>{diffResult.years} years</span>
                <span>{diffResult.months} months</span>
                <span>{diffResult.days} days</span>
              </div>
              <p className="text-xs text-muted-foreground">
                Total duration: <span className="font-semibold text-foreground">{diffResult.totalDays.toLocaleString()} days</span>
              </p>
            </div>
          )}
        </div>
      )}
    </div>
  );
}